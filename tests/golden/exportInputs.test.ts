/// <reference types="node" />
// Writes tests/golden/inputs.json: the exact initial states the golden data is computed from, so
// tools/reference/make_golden.py (REBOUND) starts from the same numbers. Skipped unless asked:
//   WRITE_GOLDEN_INPUTS=1 npx vitest run tests/golden/exportInputs.test.ts
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { FIGURE_EIGHT } from '../../src/presets/figureEight';
import { instantiate } from '../../src/presets/schema';
import { shiftToComFrame } from '../../src/sim/coords';
import type { SystemState } from '../../src/sim/types';
import { hierarchical, kepler, pythagorean } from '../helpers';

const dump = (s: SystemState, extra: Record<string, unknown>): Record<string, unknown> => ({
  m: Array.from(s.m),
  x: Array.from(s.x),
  v: Array.from(s.v),
  G: s.G,
  ...extra,
});

it.runIf(process.env.WRITE_GOLDEN_INPUTS === '1')('writes the golden inputs', () => {
  const eight = instantiate(FIGURE_EIGHT).state;
  shiftToComFrame(eight);
  const { s: h, T1 } = hierarchical();
  const k = kepler(0.5, 1);
  const inputs = {
    note: 'Initial states for the REBOUND golden data. Generated by tests/golden/exportInputs.test.ts; do not edit.',
    'figure-eight': dump(eight, { period: FIGURE_EIGHT.period, times: [FIGURE_EIGHT.period! / 2, FIGURE_EIGHT.period, 2 * FIGURE_EIGHT.period!] }),
    pythagorean: dump(pythagorean(), { times: [2, 5, 10, 20, 30] }),
    hierarchical: dump(h, { period: T1, dt: T1 / 20, steps: [200, 2000] }),
    kepler: dump(k.s, { period: k.T, dt: k.T / 200, steps: [200, 2000] }),
  };
  writeFileSync('tests/golden/inputs.json', JSON.stringify(inputs, null, 1) + '\n');
});
